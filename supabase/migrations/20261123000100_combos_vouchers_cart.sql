ALTER TABLE antam.khuyen_mai ADD COLUMN IF NOT EXISTS target_ids_json TEXT NOT NULL DEFAULT '[]';
ALTER TABLE antam.chi_tiet_don_hang ADD COLUMN IF NOT EXISTS combo_id INTEGER REFERENCES antam.combo_san_pham(id);
ALTER TABLE antam.chi_tiet_don_hang ADD COLUMN IF NOT EXISTS combo_name TEXT NOT NULL DEFAULT '';
