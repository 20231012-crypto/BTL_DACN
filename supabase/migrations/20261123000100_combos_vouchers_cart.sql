-- Combo sản phẩm, chọn sản phẩm thanh toán trong giỏ hàng và phạm vi áp dụng khuyến mãi.
-- Chạy an toàn nhiều lần (idempotent).
CREATE TABLE IF NOT EXISTS antam.combo_san_pham (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  image TEXT NOT NULL DEFAULT '',
  price INTEGER NOT NULL CHECK (price >= 0),
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS antam.combo_san_pham_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  combo_id BIGINT NOT NULL REFERENCES antam.combo_san_pham(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  product_id BIGINT NOT NULL REFERENCES antam.thuoc(id) DEFERRABLE INITIALLY IMMEDIATE,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  UNIQUE (combo_id, product_id)
);

CREATE TABLE IF NOT EXISTS antam.chi_tiet_gio_hang_combo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_id BIGINT NOT NULL REFERENCES antam.gio_hang(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  combo_id BIGINT NOT NULL REFERENCES antam.combo_san_pham(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  selected INTEGER NOT NULL DEFAULT 1,
  UNIQUE (cart_id, combo_id)
);

ALTER TABLE antam.chi_tiet_gio_hang ADD COLUMN IF NOT EXISTS selected INTEGER NOT NULL DEFAULT 1;
ALTER TABLE antam.khuyen_mai ADD COLUMN IF NOT EXISTS apply_scope TEXT NOT NULL DEFAULT 'order';
ALTER TABLE antam.khuyen_mai ADD COLUMN IF NOT EXISTS target_ids_json TEXT NOT NULL DEFAULT '[]';
ALTER TABLE antam.chi_tiet_don_hang ADD COLUMN IF NOT EXISTS combo_id BIGINT REFERENCES antam.combo_san_pham(id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE antam.chi_tiet_don_hang ADD COLUMN IF NOT EXISTS combo_name TEXT NOT NULL DEFAULT '';

REVOKE ALL ON antam.combo_san_pham FROM PUBLIC;
REVOKE ALL ON antam.combo_san_pham_item FROM PUBLIC;
REVOKE ALL ON antam.chi_tiet_gio_hang_combo FROM PUBLIC;
