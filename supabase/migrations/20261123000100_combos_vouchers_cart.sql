CREATE TABLE IF NOT EXISTS antam.combo_san_pham (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  image TEXT NOT NULL DEFAULT '',
  price INTEGER NOT NULL CHECK (price >= 0),
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::TEXT),
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS antam.combo_san_pham_item (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  combo_id INTEGER NOT NULL REFERENCES antam.combo_san_pham(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES antam.thuoc(id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  UNIQUE (combo_id, product_id)
);

CREATE TABLE IF NOT EXISTS antam.chi_tiet_gio_hang_combo (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cart_id INTEGER NOT NULL REFERENCES antam.gio_hang(id) ON DELETE CASCADE,
  combo_id INTEGER NOT NULL REFERENCES antam.combo_san_pham(id) ON DELETE CASCADE,
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  selected INTEGER NOT NULL DEFAULT 1,
  UNIQUE (cart_id, combo_id)
);

ALTER TABLE antam.chi_tiet_gio_hang ADD COLUMN IF NOT EXISTS selected INTEGER NOT NULL DEFAULT 1;
