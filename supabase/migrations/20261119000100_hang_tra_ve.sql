-- Theo dõi hàng trả về (hàng back): mỗi yêu cầu đổi trả đã duyệt có một dòng theo dõi
-- từ lúc chờ khách gửi hàng cho đến khi nhập lại kho hoặc loại bỏ. Chạy an toàn nhiều lần.
CREATE TABLE IF NOT EXISTS antam.hang_tra_ve (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL UNIQUE REFERENCES antam.yeu_cau_huy_hoan(id) DEFERRABLE INITIALLY IMMEDIATE,
  order_id BIGINT NOT NULL REFERENCES antam.don_hang(id) DEFERRABLE INITIALLY IMMEDIATE,
  status TEXT NOT NULL DEFAULT 'awaiting' CHECK (status IN ('awaiting','in_transit','received','restocked','discarded')),
  carrier TEXT NOT NULL DEFAULT '',
  tracking_code TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  handler_id BIGINT REFERENCES antam.nguoi_dung(id) DEFERRABLE INITIALLY IMMEDIATE,
  received_at TEXT,
  inspected_at TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  updated_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_hang_tra_ve_status ON antam.hang_tra_ve(status, id);
REVOKE ALL ON antam.hang_tra_ve FROM PUBLIC;
